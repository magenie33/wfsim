#!/usr/bin/env python3
"""The cards of every category the builder does not hold yet, entered rough.

Writes `data/catalogue/<slot>.yaml` for each `holds: placeholder` slot in
`data/equipment_slots.yaml`, and the Chinese overlay
`data/i18n/zh/catalogue.yaml`, from DE's Public Export (`scripts/de_export.py`,
joined on uniqueName). Nothing written here is applied by a fight: a card
leaves its catalogue file for a modelled directory the day the engine reads it.

Usage:
  python scripts/catalogue.py
"""
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import de_export  # noqa: E402
from de_i18n import card_text, clean_line  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "catalogue"
ZH = ROOT / "data" / "i18n" / "zh" / "catalogue.yaml"

POLARITY = {"AP_ATTACK": "madurai", "AP_DEFENSE": "vazarin", "AP_TACTIC": "naramon",
            "AP_POWER": "zenurik", "AP_WARD": "unairu", "AP_PRECEPT": "penjaga",
            "AP_UMBRA": "umbra", "AP_UNIVERSAL": "universal"}

# WHICH EXPORT ROWS A SLOT TAKES. `kind` is what the card is in the game: the
# Amp seats arcanes and the Railjack's Plexus seats avionics, not mods.
PICK = {
    "archwing": ("mod", "ExportUpgrades", lambda r: r.get("type") == "ARCHWING"),
    "archmelee": ("mod", "ExportUpgrades", lambda r: r.get("type") == "ARCH-MELEE"),
    "necramech": ("mod", "ExportUpgrades", lambda r: r.get("compatName") == "Necramech"),
    "parazon": ("mod", "ExportUpgrades", lambda r: r.get("type") == "PARAZON"),
    "k_drive": ("mod", "ExportUpgrades", lambda r: r.get("compatName") == "K-Drive"),
    "amp": ("arcane", "ExportRelicArcane",
            lambda r: r["uniqueName"].startswith("/Lotus/Upgrades/CosmeticEnhancers/OperatorAmps/")),
    "railjack": ("avionic", "ExportAvionics", lambda r: r.get("name") != "Unfused Artifact"),
}


class Dumper(yaml.SafeDumper):
    pass


# ONE LINE PER VALUE, double-quoted with escaped newlines: engine/build.rs
# strips comments line by line, and a block scalar or a '#' inside one reads
# as one.
Dumper.add_representer(str, lambda d, v: d.represent_scalar(
    "tag:yaml.org,2002:str", v, style='"' if any(c in v for c in "\n#:'") else None))


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower().replace("'", "")).strip("_")


def text_of(row: dict) -> str:
    """The card at its top rank, the rule DE opens it with first."""
    lead = "\n".join(clean_line(d) for d in row.get("description") or [] if clean_line(d))
    ranks = row.get("levelStats") or []
    top = card_text(ranks[-1]["stats"]) if ranks else ""
    return "\n".join(x for x in (lead, top if top != lead else "") if x)


def rows(slot: str) -> list[dict]:
    kind, category, keep = PICK[slot]
    seen, out = {}, []
    for r in de_export.categories("en")[category]:
        if not keep(r) or r.get("excludeFromCodex"):
            continue
        i = slug(r["name"])
        if i in seen:
            continue
        seen[i] = r["uniqueName"]
        card = {"id": i, "name": r["name"], "internal_name": r["uniqueName"]}
        if r.get("rarity"):
            card["rarity"] = r["rarity"].lower()
        if kind != "arcane":
            card["polarity"] = POLARITY[r.get("polarity", "AP_UNIVERSAL")]
            card["base_drain"] = r.get("baseDrain", 0)
            card["max_rank"] = r.get("fusionLimit", 0)
        else:
            card["max_rank"] = max(len(r.get("levelStats") or []) - 1, 0)
        card["description"] = text_of(r)
        out.append(card)
    return sorted(out, key=lambda c: c["id"])


def main() -> int:
    slots = yaml.safe_load((ROOT / "data" / "equipment_slots.yaml").read_text(encoding="utf-8"))["slots"]
    zh_items = de_export.items("zh")
    zh_names, zh_text = {}, {}
    OUT.mkdir(parents=True, exist_ok=True)
    for s in slots:
        if s["holds"] != "placeholder":
            continue
        kind = PICK[s["id"]][0]
        cards = rows(s["id"])
        head = (f"# {s['name'].upper()} — the {kind}s this category takes, entered rough.\n"
                "#\n# GENERATED by scripts/catalogue.py from DE's Public Export — DO NOT HAND-EDIT.\n"
                "# NOTHING HERE IS SIMULATED: a card leaves this file for a modelled\n"
                "# directory the day the engine applies it.\n")
        body = yaml.dump({"slot": s["id"], "kind": kind, "cards": cards},
                              Dumper=Dumper, allow_unicode=True, sort_keys=False, width=100000)
        (OUT / f"{s['id']}.yaml").write_text(head + body, encoding="utf-8", newline="\n")
        for c in cards:
            z = zh_items.get(c["internal_name"])
            if not z:
                continue
            key = f"{s['id']}/{c['id']}"
            if z.get("name") and z["name"] != c["name"]:
                zh_names[key] = z["name"]
            t = text_of(z)
            if t and t != c["description"]:
                zh_text[key] = t
        print(f"{s['id']}: {len(cards)} {kind}s", file=sys.stderr)
    head = ("# zh — the rough catalogue's names and card text, in DE's OWN words.\n"
            "#\n# GENERATED by scripts/catalogue.py — DO NOT HAND-EDIT. Keyed `<slot>/<id>`\n"
            "# (data/catalogue/<slot>.yaml), joined on internal_name == uniqueName.\n")
    body = yaml.dump({"catalogue": zh_names, "catalogue_descriptions": zh_text},
                          Dumper=Dumper, allow_unicode=True, sort_keys=True, width=100000)
    ZH.write_text(head + body, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
