// Compute layout, pagination and the shared live device count.
// WFSIM_BASE points at the native dev server; CI also runs against the built site.
import { openApp } from "./cdp.mjs";

const app = await openApp({ boot: 13000, base: process.env.WFSIM_BASE, lang: "en" });
const { evaluate, check } = app;
const ui = await evaluate(`(async () => {
  const wait = () => new Promise(resolve => setTimeout(resolve, 150));
  history.pushState({}, "", "/compute"); route(); await wait();
  clearInterval(computeTimer); computeTimer = setInterval(() => {}, 60000);
  accountState.loaded = true; accountState.providers = ["email"]; accountState.account = { id: "paged-account" };
  computeAskedFor = "paged-account";
  const hours = Array.from({ length: 25 }, (_, i) => ({ hour: new Date(Date.now() - i * 86400000).toISOString().slice(0, 13), tasks: i + 1, points: i + 1, holder: "you", id: "paged-device" }));
  ledgerHere = { summary: { points: 325, device: 0, you: 325, other: 0 }, unpaid: {}, earlier: true, hours };
  ledgerAccount = { devices: [{ id: "paged-device", label: "Paged device" }], hours };
  devicesState = { points: 325, recent: 325, devices: Array.from({ length: 25 }, (_, i) => ({ id: "device" + i, label: "Device " + i, points: i, recent: i })) };
  localStorage.setItem(COMPUTE_LOG_KEY, JSON.stringify(Array.from({ length: 25 }, (_, i) => ({ kind: "unknown", at: Date.now() - i * 60000, ms: 1000, work: 1e9, state: "confirmed" }))));
  computeJustDone = null;
  renderAuthPage("compute"); await wait();
  const out = {};
  out.contributors = !!document.querySelector('#compute-intro a[href="/contributors"]');
  const rows = id => document.querySelectorAll('#' + id + ' tbody > tr').length;
  out.first = [rows("compute-ledger"), rows("compute-account-ledger"), document.querySelectorAll('#rt-live .rt-card').length];
  if (!document.querySelector('#compute-workspace [data-layout-edit]')) return out;
  const next = key => document.querySelector('[data-page-key="' + key + '"][data-page="1"]').click();
  const firstDay = document.querySelector('#compute-ledger .lg-day').textContent;
  next("ledger:here"); await wait();
  out.changedDay = firstDay !== document.querySelector('#compute-ledger .lg-day').textContent;
  next("ledger:account"); next("recent"); next("devices"); await wait();
  const before = document.querySelector('#compute-ledger .lg-day').textContent;
  renderAuthPage("compute"); await wait();
  out.keptPages = before === document.querySelector('#compute-ledger .lg-day').textContent && computePages.recent === 1 && computePages.devices === 1;
  document.querySelector('[data-page-key="ledger:here"][data-page="2"]').click(); await wait();
  out.last = rows("compute-ledger");
  document.querySelector('#compute-workspace [data-layout-reset]').click(); await wait();
  document.querySelector('#compute-workspace [data-layout-edit]').click(); await wait();
  const live = document.getElementById("rt-live"), browser = document.getElementById("compute-browser");
  const baseline = browser.getBoundingClientRect().width;
  live.querySelector('[data-layout-up]').click();
  browser.querySelector('.layout-size-handle').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  await wait();
  renderAuthPage("compute"); await wait();
  out.layoutKept = document.querySelector('#compute-workspace > .block') === live && document.getElementById("rt-live") === live && browser.getBoundingClientRect().width < baseline;
  const after = JSON.parse(localStorage.getItem('wfsim-layout'));
  out.saved = !!after.cards['compute-browser'] && after.orders['compute-workspace:page'][0] === 'rt-live';
  ledgerHere = null; renderAuthPage("compute"); await wait();
  ledgerHere = { summary: { points: 325, device: 0, you: 325, other: 0 }, unpaid: {}, hours };
  renderAuthPage("compute"); await wait();
  document.querySelector('#compute-workspace [data-layout-reset]').click(); await wait();
  out.reset = [...document.querySelectorAll('#compute-workspace > .block')].map(el => el.id).slice(0, 5).join(',') === 'compute-browser,rt-live,compute-devices,compute-ledger,compute-account-ledger' && browser.style.width === '';
  const oldTally = tallyTo, oldFrom = tallyFrom, oldCount = computingCount;
  tallyTo = { volunteers: 1, official: 2, computing: 999 }; tallyFrom = tallyTo;
  computingCount = 7;
  document.getElementById('compute-count').hidden = false;
  document.getElementById('compute-count').textContent = computeCount(computingCount);
  computeLinkPaint(); renderHomeTally(); renderSupportCounts();
  out.sameCount = document.querySelector('#home-tally-n .hf:last-child b').textContent === document.getElementById('compute-count').textContent && document.getElementById('support-computing').textContent.startsWith('7 ');
  out.oneLink = document.getElementById('compute-count').closest('a') === document.getElementById('compute-mark').closest('a') && document.getElementById('compute-link').getAttribute('href') === '/compute';
  computingCount = 0; renderHomeTally();
  out.zero = document.querySelector('#home-tally-n .hf:last-child b').textContent === '0';
  tallyTo = oldTally; tallyFrom = oldFrom; computingCount = oldCount;
  return out;
})()`);
check("compute ledgers and recent tasks show ten entries per page", ui.first.every(n => n === 10), JSON.stringify(ui));
check("ledger pages advance, keep their place across refreshes and end with the remaining rows", ui.changedDay && ui.keptPages && ui.last === 5, JSON.stringify(ui));
check("compute cards share saved resizing and order while the live node stays mounted", ui.layoutKept && ui.saved, JSON.stringify(ui));
check("default layout restores authored order after a ledger is removed and returns", ui.reset, JSON.stringify(ui));
check("home and support use the nav's live device count, including zero", ui.sameCount && ui.zero, JSON.stringify(ui));
check("the ring and device count share one link, and compute has a contributors entry", ui.oneLink && ui.contributors, JSON.stringify(ui));

await app.finish("compute cards, pages and live counts agree");
